def markdown_to_semantic_html(md):
    lines = md.strip().split("\n")
    html_out = []
    in_table = False
    table_headers = []
    table_rows = []
    in_list = False
    list_items = []
    in_quote = False
    quote_lines = []

    def flush_list():
        nonlocal in_list, list_items, html_out
        if in_list and list_items:
            html_out.append('<ul class="list-disc pl-5 my-4 space-y-2">')
            for it in list_items:
                html_out.append(f'  <li class="text-[15px] leading-relaxed text-[#334155]">{it}</li>')
            html_out.append('</ul>')
            in_list = False
            list_items = []

    def flush_table():
        nonlocal in_table, table_headers, table_rows, html_out
        if in_table:
            html_out.append('<div class="overflow-x-auto my-6">')
            html_out.append('  <table class="w-full text-left border-collapse border border-slate-300 rounded-lg">')
            if table_headers:
                html_out.append('    <thead>')
                html_out.append('      <tr>')
                for th in table_headers:
                    html_out.append(f'        <th class="border border-slate-300 bg-slate-100 px-4 py-3 font-bold text-slate-800 text-[14px]">{th}</th>')
                html_out.append('      </tr>')
                html_out.append('    </thead>')
            if table_rows:
                html_out.append('    <tbody>')
                for row in table_rows:
                    html_out.append('      <tr class="border-b border-slate-200 hover:bg-slate-50">')
                    for cell in row:
                        html_out.append(f'        <td class="border border-slate-200 px-4 py-3 text-slate-700 text-[14px]">{cell}</td>')
                    html_out.append('      </tr>')
                html_out.append('    </tbody>')
            html_out.append('  </table>')
            html_out.append('</div>')
            in_table = False
            table_headers = []
            table_rows = []

    def flush_quote():
        nonlocal in_quote, quote_lines, html_out
        if in_quote and quote_lines:
            html_out.append('<div class="p-4 bg-slate-50 border-l-4 border-[#0f766e] rounded-r-lg my-4 text-slate-700 leading-relaxed font-medium">')
            for ql in quote_lines:
                html_out.append(f'  <p class="mb-1 text-[15px]">{ql}</p>')
            html_out.append('</div>')
            in_quote = False
            quote_lines = []

    for line in lines:
        stripped = line.strip()
        if not stripped:
            flush_list()
            flush_table()
            flush_quote()
            continue

        if stripped.startswith(">"):
            flush_list()
            flush_table()
            in_quote = True
            content = stripped.lstrip(">").strip()
            # replace bold
            content = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', content)
            quote_lines.append(content)
            continue
        else:
            flush_quote()

        if stripped.startswith("|"):
            flush_list()
            # Check if divider line
            if re.match(r'^\|[\s\-:|]+\|$', stripped):
                continue
            cells = [c.strip() for c in stripped.split("|")[1:-1]]
            if not in_table:
                in_table = True
                table_headers = cells
            else:
                table_rows.append(cells)
            continue
        else:
            flush_table()

        if stripped.startswith("## "):
            flush_list()
            title = stripped[3:].strip()
            html_out.append(f'<h2 class="text-2xl font-extrabold text-[#111827] mt-8 mb-4 border-b border-slate-200 pb-2 break-keep">{title}</h2>')
            continue

        if stripped.startswith("### "):
            flush_list()
            title = stripped[4:].strip()
            html_out.append(f'<h3 class="text-xl font-bold text-[#1e293b] mt-6 mb-3 break-keep">{title}</h3>')
            continue

        if re.match(r'^[-*]\s+', stripped) or re.match(r'^\d+\.\s+', stripped):
            in_list = True
            item_text = re.sub(r'^[-*]\s+|\d+\.\s+', '', stripped)
            item_text = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', item_text)
            list_items.append(item_text)
            continue
        else:
            flush_list()

        # Regular paragraph
        p_text = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', stripped)
        html_out.append(f'<p class="text-[15.5px] leading-relaxed text-[#334155] mb-4 break-keep">{p_text}</p>')

    flush_list()
    flush_table()
    flush_quote()

    # Prepend professional badge & lead
    return "\n".join(html_out)

